def emit(name, rows):
    out = []
    for slug, nm, country, region, city, cat, desc, wps, km, diff in rows:
        assert cat in CATEGORIES, f"{slug}: bad category {cat}"
        assert 1 <= diff <= 5, f"{slug}: bad difficulty"
        assert 2 <= len(wps) <= 5, f"{slug}: bad waypoint count"
        out.append({
            "slug": slug, "name": nm, "country": country, "region": region,
            "city": city, "category": cat, "description": desc,
            "waypoints": wps, "expectedKm": km, "difficultyHint": diff,
        })
    path = pathlib.Path(__file__).parent / "manifest" / name
    path.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n")
    print(f"{name}: {len(out)}")
    return len(out)


